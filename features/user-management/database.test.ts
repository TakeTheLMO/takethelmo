import { afterEach, describe, expect, it } from "vitest";
import { LocalAuthStore } from "../local-auth/database";
import { AccountDataStore } from "./database";
import { createSeed } from "../demo/data";
import { contentRecords } from "./records";
import { emptyWorkspace } from "../workspace/state";
let auth: LocalAuthStore;
afterEach(() => auth?.db.close());
function setup() {
  auth = new LocalAuthStore(":memory:"); auth.ensureAdmin();
  const admin = auth.login("admin", "admin"), owner = auth.register("홍연구", "owner@example.com", "password123"), other = auth.register("김연구", "other@example.com", "password123", "safety_admin");
  return { admin, owner, other, store: new AccountDataStore(auth.db) };
}
describe("administrator account and shared records", () => {
  it("categorizes lab, courses, responses and linked uploads and audits targeted corrections", () => {
    const { admin, owner, other, store } = setup();
    const state = emptyWorkspace("researcher");
    state.lab = { name: "신규 연구실", location: "1층", code: "L-1", description: "등록 설명" };
    state.courses.push({ id: "course", title: "안전교육", category: "정기", duration: "2시간", due: "", description: "" });
    state.assessment = { organism: "아니요" };
    store.putFile(owner.id, "certificate", "수료증.pdf", "application/pdf", Buffer.from("test"));
    state.enrollments.push({ courseId: "course", owner: "researcher", status: "등록 완료", at: new Date().toISOString(), completedAt: "2026-11-17", file: { id: "certificate", name: "수료증.pdf", type: "application/pdf", size: 4 } });
    store.save(owner.id, state, 0);
    expect(store.allRecords(admin.id).map(row => row.category)).toEqual(expect.arrayContaining(["lab", "courses", "enrollments", "assessment"]));
    expect(store.allFiles(admin.id)[0].records[0]).toMatchObject({ category: "enrollments", title: "안전교육" });
    expect(() => store.allFiles(other.id)).toThrow("관리자");
    store.updateRecord(admin.id, owner.id, { category: "lab", key: "lab", revision: 1, fields: { location: "2층" }, reason: "실제 위치 확인" });
    store.updateRecord(admin.id, owner.id, { category: "courses", key: "course", revision: 2, fields: { due: "2026-12-01" }, reason: "기한 안내" });
    store.updateRecord(admin.id, owner.id, { category: "assessment", key: "assessment", revision: 3, fields: { answers: { organism: "모르겠어요" } }, reason: "연구자 요청 정정" });
    expect(store.snapshot(owner.id).state).toMatchObject({ lab: { location: "2층" }, assessment: { organism: "모르겠어요" } });
    expect(store.detail(admin.id, owner.id).history.some(row => row.reason === "실제 위치 확인")).toBe(true);
    expect(() => store.updateRecord(admin.id, owner.id, { category: "lab", key: "lab", revision: 4, fields: { role: "super_admin" }, reason: "위조" })).toThrow("수정할 수 없는");
  });
  it("excludes untouched examples and records only actual submissions", () => {
    const { owner, admin, store } = setup();
    const state = createSeed();
    expect(contentRecords(state)).toEqual([]);
    store.save(owner.id, state, 0);
    expect(store.activity(admin.id).events).toHaveLength(0);
    state.requests.push({ ...state.requests[0], id: "actual-request", title: "실제 입력 내용" });
    store.save(owner.id, state, 1);
    expect(store.detail(admin.id, owner.id).records[0].title).toBe("실제 입력 내용");
    expect(store.activity(admin.id).unread).toBe(1);
    expect(store.users(admin.id, "홍연구")).toHaveLength(1);
    expect(JSON.stringify(store.users(admin.id))).not.toContain("password_hash");
  });
  it("enforces admin-only access, owner file scope and stale record rejection", () => {
    const { owner, other, admin, store } = setup();
    const state = createSeed(); state.requests.push({ ...state.requests[0], id: "actual", title: "원래 제목" });
    store.save(owner.id, state, 0);
    expect(() => store.users(other.id)).toThrow("관리자");
    expect(() => store.detail(other.id, owner.id)).toThrow("관리자");
    store.putFile(owner.id, "file-one", "test.pdf", "application/pdf", Buffer.from("example"));
    expect(() => store.file(other.id, owner.id, "file-one")).toThrow("관리자");
    expect(store.file(admin.id, owner.id, "file-one").name).toBe("test.pdf");
    store.updateRecord(admin.id, owner.id, { category: "requests", key: "actual", revision: 1, fields: { title: "관리자가 정정한 제목" }, reason: "오탈자 수정" });
    expect(store.snapshot(owner.id).state?.requests.at(-1)?.title).toBe("관리자가 정정한 제목");
    expect(() => store.save(owner.id, state, 1)).toThrow("다른 변경");
    expect(store.detail(admin.id, owner.id).history.some(row => row.reason === "오탈자 수정")).toBe(true);
    const ids = store.activity(admin.id).events.map(row => String(row.id)); store.readActivity(admin.id, ids);
    expect(store.activity(admin.id).unread).toBe(0);
  });
  it("updates accounts, protects admin and revokes deactivated sessions", () => {
    const { owner, other, admin, store } = setup();
    const session = auth.session(owner);
    const profile = store.detail(admin.id, owner.id).user;
    expect(() => store.updateUser(other.id, owner.id, {})).toThrow("관리자");
    expect(() => store.detail(admin.id, admin.id)).toThrow("사용자");
    store.updateUser(admin.id, owner.id, { original: profile, name: "정정 연구자", email: "new@example.com", role: "lmo_manager", active: true, note: "참조 메모", reason: "정보 확인" });
    expect(auth.user(session)).toMatchObject({ name: "정정 연구자", role: "lmo_manager" });
    expect(store.detail(admin.id, owner.id).note).toBe("참조 메모");
    store.updateUser(admin.id, owner.id, { original: store.detail(admin.id, owner.id).user, name: "정정 연구자", email: "new@example.com", role: "lmo_manager", active: false, reason: "퇴실 처리" });
    expect(auth.user(session)).toBeNull();
  });
  it("requires administrator review and preserves owner resubmission and completed records", () => {
    const { owner, admin, store } = setup();
    const state = createSeed(); state.requests.push({ ...state.requests[0], id: "live-request", title: "실제 신청" });
    store.save(owner.id, state, 0);
    const forged = structuredClone(store.snapshot(owner.id).state!); forged.requests[0].status = "승인";
    expect(() => store.save(owner.id, forged, 1)).toThrow("직접 변경");
    store.updateRecord(admin.id, owner.id, { category: "requests", key: "live-request", revision: 1, fields: { status: "검토 중" }, reason: "검토 시작" });
    store.updateRecord(admin.id, owner.id, { category: "requests", key: "live-request", revision: 2, fields: { status: "보완 요청" }, reason: "일정을 보완해 주세요" });
    const resubmit = structuredClone(store.snapshot(owner.id).state!);
    resubmit.requests[0].status = "제출"; resubmit.requests[0].body = "보완한 일정입니다.";
    resubmit.requests[0].history.push({ at: new Date().toISOString(), actor: owner.name, event: "보완 후 재제출", note: "일정 보완" });
    store.save(owner.id, resubmit, 3);
    store.updateRecord(admin.id, owner.id, { category: "requests", key: "live-request", revision: 4, fields: { status: "검토 중" }, reason: "재검토" });
    store.updateRecord(admin.id, owner.id, { category: "requests", key: "live-request", revision: 5, fields: { status: "승인" }, reason: "내부 검토 완료" });
    const approved = store.snapshot(owner.id).state!;
    expect(approved.requests[0].status).toBe("승인");
    expect(() => store.save(owner.id, { ...approved, requests: [] }, 6)).toThrow("삭제할 수 없습니다");
    expect(store.snapshot(owner.id).state?.requests[0].status).toBe("승인");
  });
});
